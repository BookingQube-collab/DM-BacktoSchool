export type MessageKey = keyof typeof en;

type Vars = Record<string, string | number>;

export function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined || vars[key] === null ? `{${key}}` : String(vars[key]),
  );
}

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const dict = locale === "ar" ? ar : en;
  return interpolate(dict[key] ?? en[key] ?? key, vars);
}

export function readStoredLocale(): Locale {
  try {
    const raw = localStorage.getItem(LANG_STORAGE_KEY);
    if (raw === "ar" || raw === "en") return raw;
  } catch {
    /* ignore */
  }
  return "en";
}

export function writeStoredLocale(locale: Locale): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, locale);
  } catch {
    /* ignore quota / private mode */
  }
}

export function applyDocumentLocale(locale: Locale): void {
  if (typeof document === "undefined") return;
  const dir = locale === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = locale;
  document.documentElement.dir = dir;
}

type I18nContextValue = {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (next: Locale) => void;
  t: (key: MessageKey, vars?: Vars) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const stored = readStoredLocale();
    setLocaleState(stored);
    applyDocumentLocale(stored);
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    writeStoredLocale(next);
    applyDocumentLocale(next);
  }, []);

  const t = useCallback((key: MessageKey, vars?: Vars) => translate(locale, key, vars), [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      dir: locale === "ar" ? "rtl" : "ltr",
      setLocale,
      t,
    }),
    [locale, setLocale, t],
  );

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    const t = (key: MessageKey, vars?: Vars) => translate("en", key, vars);
    return {
      locale: "en",
      dir: "ltr",
      setLocale: () => {},
      t,
    };
  }
  return ctx;
}
